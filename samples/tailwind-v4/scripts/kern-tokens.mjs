// Writes src/kern-tokens.css and src/kern-remap.css from the installed
// @kern-ux/native and tailwindcss. With --check it writes nothing: it fails
// when either file is out of date or a stylesheet in src/ names a KERN
// custom property that KERN doesn't define, which is how a renamed token
// shows up after a KERN update.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const read = (path) => readFileSync(new URL(path, root), "utf8");

const kernVersion = JSON.parse(
	read("node_modules/@kern-ux/native/package.json"),
).version;
const kernCss = read("node_modules/@kern-ux/native/dist/kern.min.css");
const tailwindTheme = read("node_modules/tailwindcss/theme.css");

// Which KERN family each Tailwind family is drawn from, by nearest hue.
// Tailwind's tinted greys go to KERN's blue-grey neutral when they lean blue,
// the rest to its pure grey.
const FAMILIES = {
	slate: "neutral",
	gray: "neutral",
	zinc: "neutral",
	neutral: "grey",
	stone: "grey",
	mauve: "grey",
	olive: "grey",
	mist: "grey",
	taupe: "grey",
	red: "red",
	rose: "red",
	pink: "red",
	orange: "orange",
	amber: "orange",
	yellow: "yellow",
	lime: "limette",
	green: "green",
	emerald: "turquois",
	teal: "turquois",
	cyan: "lightblue",
	sky: "lightblue",
	blue: "darkblue",
	indigo: "darkblue",
	violet: "violet",
	purple: "violet",
	fuchsia: "violet",
};

// KERN has three radii and three elevations; Tailwind's larger steps take
// KERN's largest so pasted cards and dialogs don't come out rounder than KERN.
const RADII = {
	xs: "small",
	sm: "default",
	md: "default",
	lg: "large",
	xl: "large",
	"2xl": "large",
	"3xl": "large",
	"4xl": "large",
};
const SHADOWS = {
	"2xs": "low",
	xs: "low",
	sm: "low",
	md: "default",
	lg: "high",
	xl: "high",
	"2xl": "high",
};

function firstDefinitions(css, pattern) {
	const found = new Map();
	for (const [, name, value] of css.matchAll(pattern)) {
		if (!found.has(name)) found.set(name, value.trim());
	}
	return found;
}

const kernColors = firstDefinitions(
	kernCss,
	/--kern-color-([a-z0-9-]+)\s*:\s*([^;}]+)/g,
);
const kernDefined = new Set(
	[...kernCss.matchAll(/(--kern-[a-zA-Z0-9-]+)\s*:/g)].map((m) => m[1]),
);

const isPrimitive = (name) => /^[a-z]+-\d{3}$|^(white|black)$/.test(name);
const isBrand = (name) => name.startsWith("brand-colorpalette-");
// action-state-opacity-* live under --kern-color- but hold numbers.
const isColor = (value) => !/^[\d.]+%?$/.test(value);

function lightness(oklch) {
	const match = /^oklch\(\s*([\d.]+)%/.exec(oklch);
	return match ? Number(match[1]) : undefined;
}

function block(title, lines) {
	return [`\t/* ${title} */`, ...lines.map((line) => `\t${line}`)].join("\n");
}

function tokensFile() {
	const names = [...kernColors]
		.filter(([, value]) => isColor(value))
		.map(([name]) => name);
	const mirror = (name) => `--color-kern-${name}: var(--kern-color-${name});`;
	return `/*
 * Generated by scripts/kern-tokens.mjs from @kern-ux/native ${kernVersion}.
 * Don't edit it by hand: run \`npm run tokens\`.
 *
 * Every KERN colour token --kern-color-<name> as the Tailwind colour
 * kern-<name>: --kern-color-action-default-contextual is
 * bg-kern-action-default-contextual.
 */
@theme inline {
${block(
	"Semantic",
	names.filter((n) => !isPrimitive(n) && !isBrand(n)).map(mirror),
)}

${block("Palette", names.filter(isPrimitive).map(mirror))}

${block("Brand palettes", names.filter(isBrand).map(mirror))}
}
`;
}

function remapFile() {
	const tailwind = new Map();
	for (const [, family, step, l] of tailwindTheme.matchAll(
		/--color-([a-z]+)-(\d+):\s*oklch\(([\d.]+)%/g,
	)) {
		if (!tailwind.has(family)) tailwind.set(family, []);
		tailwind.get(family).push({ step, l: Number(l) });
	}
	const unmapped = [...tailwind.keys()].filter((f) => !(f in FAMILIES));
	if (unmapped.length > 0) {
		throw new Error(
			`Tailwind families without a KERN family: ${unmapped.join(", ")}. Add them to FAMILIES.`,
		);
	}

	const kernSteps = (family) =>
		[...kernColors]
			.filter(([name]) => new RegExp(`^${family}-\\d{3}$`).test(name))
			.map(([name, value]) => ({ name, l: lightness(value) }));

	const families = [...tailwind].map(([family, steps]) => {
		const candidates = kernSteps(FAMILIES[family]);
		if (candidates.length === 0 || candidates.some((c) => c.l === undefined)) {
			throw new Error(`KERN palette ${FAMILIES[family]} has no OKLCH steps.`);
		}
		const lines = steps.map(({ step, l }) => {
			// Ties go to the darker step, which has the higher contrast on white.
			const nearest = candidates.reduce((best, c) =>
				Math.abs(c.l - l) <= Math.abs(best.l - l) ? c : best,
			);
			return `--color-${family}-${step}: var(--kern-color-${nearest.name});`;
		});
		return block(`${family} → ${FAMILIES[family]}`, lines);
	});

	return `/*
 * Generated by scripts/kern-tokens.mjs from @kern-ux/native ${kernVersion}.
 * Don't edit it by hand: run \`npm run tokens\`.
 *
 * Points Tailwind's default palette, radii and shadows at KERN, for
 * components that hard-code them (bg-indigo-600, rounded-lg, shadow-sm).
 * Each Tailwind step takes the step of its KERN family with the nearest
 * OKLCH lightness, so a pair like text-gray-500 on bg-gray-50 keeps about
 * the contrast its author chose.
 */
@theme inline {
${families.join("\n\n")}

${block(
	"Radii",
	Object.entries(RADII).map(
		([tw, kern]) => `--radius-${tw}: var(--kern-metric-border-radius-${kern});`,
	),
)}

${block(
	"Shadows",
	Object.entries(SHADOWS).map(
		([tw, kern]) => `--shadow-${tw}: var(--kern-shadow-elevation-${kern});`,
	),
)}
}
`;
}

const outputs = {
	"src/kern-tokens.css": tokensFile(),
	"src/kern-remap.css": remapFile(),
};

if (!process.argv.includes("--check")) {
	for (const [path, content] of Object.entries(outputs)) {
		writeFileSync(new URL(path, root), content);
		console.log(`wrote ${path}`);
	}
	process.exit(0);
}

const problems = [];
for (const [path, content] of Object.entries(outputs)) {
	if (read(path) !== content) {
		problems.push(`${path} is out of date: run \`npm run tokens\`.`);
	}
}
for (const file of readdirSync(new URL("src/", root))) {
	if (!file.endsWith(".css")) continue;
	const used = new Set(
		[...read(`src/${file}`).matchAll(/var\((--kern-[a-zA-Z0-9-]+)/g)].map(
			(m) => m[1],
		),
	);
	for (const name of used) {
		if (!kernDefined.has(name)) {
			problems.push(
				`src/${file} uses ${name}, which @kern-ux/native ${kernVersion} doesn't define.`,
			);
		}
	}
}
if (problems.length > 0) {
	console.error(problems.join("\n"));
	process.exit(1);
}
console.log(
	`KERN ${kernVersion}: generated files are current, every token exists.`,
);
