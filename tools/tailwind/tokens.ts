/**
 * Builds packages/tailwind/src/tokens.css and remap.css from the installed
 * @kern-ux/native and tailwindcss, and finds KERN custom properties that a
 * stylesheet names but KERN doesn't define, which is how a renamed token
 * shows up after a KERN update. tools/tailwind/generate.ts writes the files;
 * tokens.test.ts checks the checked-in ones.
 */
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const PACKAGE_SRC = fileURLToPath(
	new URL("../../packages/tailwind/src/", import.meta.url),
);

/** The generated files, by name in PACKAGE_SRC. */
export type GeneratedFiles = Record<"tokens.css" | "remap.css", string>;

export type Sources = {
	/** @kern-ux/native's dist/kern.min.css */
	kernCss: string;
	/** tailwindcss's theme.css, with its default palette */
	tailwindTheme: string;
};

const require = createRequire(import.meta.url);

function packageFile(name: string, file: string): string {
	const dir = path.dirname(require.resolve(`${name}/package.json`));
	return readFileSync(path.join(dir, file), "utf8");
}

export function installedSources(): Sources & { kernVersion: string } {
	return {
		kernCss: packageFile("@kern-ux/native", "dist/kern.min.css"),
		kernVersion: JSON.parse(packageFile("@kern-ux/native", "package.json"))
			.version,
		tailwindTheme: packageFile("tailwindcss", "theme.css"),
	};
}

/**
 * Which KERN family each Tailwind family is drawn from, by nearest hue.
 * Tailwind's tinted greys go to KERN's blue-grey neutral when they lean blue,
 * the rest to its pure grey.
 */
export const FAMILIES: Record<string, string> = {
	slate: "neutral",
	gray: "neutral",
	zinc: "neutral",
	neutral: "grey",
	stone: "grey",
	mauve: "grey",
	olive: "grey",
	mist: "grey",
	taupe: "grey",
	red: "red",
	rose: "red",
	pink: "red",
	orange: "orange",
	amber: "orange",
	yellow: "yellow",
	lime: "limette",
	green: "green",
	emerald: "turquois",
	teal: "turquois",
	cyan: "lightblue",
	sky: "lightblue",
	blue: "darkblue",
	indigo: "darkblue",
	violet: "violet",
	purple: "violet",
	fuchsia: "violet",
};

/**
 * KERN has three radii and three elevations; Tailwind's larger steps take
 * KERN's largest so pasted cards and dialogs don't come out rounder than KERN.
 */
const RADII: Record<string, string> = {
	xs: "small",
	sm: "default",
	md: "default",
	lg: "large",
	xl: "large",
	"2xl": "large",
	"3xl": "large",
	"4xl": "large",
};
const SHADOWS: Record<string, string> = {
	"2xs": "low",
	xs: "low",
	sm: "low",
	md: "default",
	lg: "high",
	xl: "high",
	"2xl": "high",
};

/** KERN's colour tokens by name after --kern-color-, first definition wins. */
function kernColors(kernCss: string): Map<string, string> {
	const found = new Map<string, string>();
	for (const [, name, value] of kernCss.matchAll(
		/--kern-color-([a-z0-9-]+)\s*:\s*([^;}]+)/g,
	)) {
		if (!found.has(name)) found.set(name, value.trim());
	}
	return found;
}

const isPrimitive = (name: string) =>
	/^[a-z]+-\d{3}$|^(white|black)$/.test(name);
const isBrand = (name: string) => name.startsWith("brand-colorpalette-");
// action-state-opacity-* live under --kern-color- but hold numbers.
const isColor = (value: string) => !/^[\d.]+%?$/.test(value);

function lightness(oklch: string): number | undefined {
	const match = /^oklch\(\s*([\d.]+)%/.exec(oklch);
	return match ? Number(match[1]) : undefined;
}

function block(title: string, lines: string[]): string {
	return [`\t/* ${title} */`, ...lines.map((line) => `\t${line}`)].join("\n");
}

const HEADER = `/*
 * Generated by tools/tailwind/generate.ts from the installed @kern-ux/native
 * and tailwindcss. Don't edit it by hand: run \`npm run tailwind:tokens\`.
 *`;

function tokensFile(colors: Map<string, string>): string {
	const names = [...colors]
		.filter(([, value]) => isColor(value))
		.map(([name]) => name);
	const mirror = (name: string) =>
		`--color-kern-${name}: var(--kern-color-${name});`;
	return `${HEADER}
 * Every KERN colour token --kern-color-<name> as the Tailwind colour
 * kern-<name>: --kern-color-action-default-contextual is
 * bg-kern-action-default-contextual.
 */
@theme inline {
${block(
	"Semantic",
	names.filter((n) => !isPrimitive(n) && !isBrand(n)).map(mirror),
)}

${block("Palette", names.filter(isPrimitive).map(mirror))}

${block("Brand palettes", names.filter(isBrand).map(mirror))}
}
`;
}

/** Tailwind's default palette: each family's steps with their OKLCH lightness. */
function tailwindPalette(
	tailwindTheme: string,
): Map<string, { step: string; l: number }[]> {
	const palette = new Map<string, { step: string; l: number }[]>();
	for (const [, family, step, l] of tailwindTheme.matchAll(
		/--color-([a-z]+)-(\d+):\s*oklch\(([\d.]+)%/g,
	)) {
		const steps = palette.get(family) ?? [];
		steps.push({ step, l: Number(l) });
		palette.set(family, steps);
	}
	return palette;
}

function remapFile(colors: Map<string, string>, tailwindTheme: string): string {
	const palette = tailwindPalette(tailwindTheme);
	const unmapped = [...palette.keys()].filter((f) => !(f in FAMILIES));
	if (unmapped.length > 0) {
		throw new Error(
			`Tailwind families without a KERN family: ${unmapped.join(", ")}. Add them to FAMILIES in tools/tailwind/tokens.ts.`,
		);
	}

	const families = [...palette].map(([family, steps]) => {
		const kernFamily = FAMILIES[family];
		const candidates = [...colors]
			.filter(([name]) => new RegExp(`^${kernFamily}-\\d{3}$`).test(name))
			.map(([name, value]) => ({ name, l: lightness(value) }));
		if (candidates.length === 0) {
			throw new Error(`KERN has no palette called ${kernFamily}.`);
		}
		const lines = steps.map(({ step, l }) => {
			// Ties go to the darker step, which has the higher contrast on white.
			const nearest = candidates.reduce((best, c) => {
				if (c.l === undefined || best.l === undefined) {
					throw new Error(`KERN's ${c.name} isn't an OKLCH colour.`);
				}
				return Math.abs(c.l - l) <= Math.abs(best.l - l) ? c : best;
			});
			return `--color-${family}-${step}: var(--kern-color-${nearest.name});`;
		});
		return block(`${family} → ${kernFamily}`, lines);
	});

	return `${HEADER}
 * Points Tailwind's default palette, radii and shadows at KERN, for
 * components that hard-code them (bg-indigo-600, rounded-lg, shadow-sm).
 * Each Tailwind step takes the step of its KERN family with the nearest
 * OKLCH lightness, so a pair like text-gray-500 on bg-gray-50 keeps about
 * the contrast its author chose.
 */
@theme inline {
${families.join("\n\n")}

${block(
	"Radii",
	Object.entries(RADII).map(
		([tw, kern]) => `--radius-${tw}: var(--kern-metric-border-radius-${kern});`,
	),
)}

${block(
	"Shadows",
	Object.entries(SHADOWS).map(
		([tw, kern]) => `--shadow-${tw}: var(--kern-shadow-elevation-${kern});`,
	),
)}
}
`;
}

export function generateFiles({
	kernCss,
	tailwindTheme,
}: Sources): GeneratedFiles {
	const colors = kernColors(kernCss);
	return {
		"tokens.css": tokensFile(colors),
		"remap.css": remapFile(colors, tailwindTheme),
	};
}

/**
 * The KERN custom properties a stylesheet reads with var() that KERN doesn't
 * define. Formatters wrap long values as `var(\n\t--kern-…)`, hence the \s*.
 */
export function undefinedKernTokens(css: string, kernCss: string): string[] {
	const defined = new Set(
		[...kernCss.matchAll(/(--kern-[a-zA-Z0-9-]+)\s*:/g)].map((m) => m[1]),
	);
	const used = new Set(
		[...css.matchAll(/var\(\s*(--kern-[a-zA-Z0-9-]+)/g)].map((m) => m[1]),
	);
	return [...used].filter((name) => !defined.has(name));
}
